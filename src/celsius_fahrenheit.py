"""
Модуль для конвертації температури між шкалами Цельсія та Фаренгейта.
"""


def celsius_to_fahrenheit(c):
    """
    Переводить температуру з Цельсія у Фаренгейт.

    Args:
        c: Температура в градусах Цельсія.

    Returns:
        Температура в градусах Фаренгейта.
    """
    return c * 9 / 5 + 32


def fahrenheit_to_celsius(f):
    """
    Переводить температуру з Фаренгейта у Цельсій.

    Args:
        f: Температура в градусах Фаренгейта.

    Returns:
        Температура в градусах Цельсія.
    """
    return (f - 32) * 5 / 9